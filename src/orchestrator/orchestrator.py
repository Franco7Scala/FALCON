# Pipeline
from typing import TypedDict, Optional
from langgraph.graph import StateGraph, END
from src.agents.request_agent import extract_information
from src.agents.query_agent import generate_query
from src.agents.response_agent import execute_and_evaluate
from src.utils.utils import DB


MAX_ATTEMPTS = 6


# Shared pipeline state
class PipelineState(TypedDict):
    user_request: str
    database_schema: str
    classification: Optional[str]  # "OUT_OF_CONTEXT" | "IN_CONTEXT"
    extracted_information: Optional[str]  # Agent 1 output
    current_query: Optional[str]  # Last query generated by Agent 2
    evaluation: Optional[str]  # "SATISFIED" | "REGENERATE"
    evaluation_feedback: Optional[str]
    improvement_attempts: int
    query_results: Optional[str]
    final_answer: Optional[str]
    outcome: Optional[str]  # "SUCCESS" | "ERROR"
    error_message: Optional[str]


def create_initial_state(user_request: str) -> PipelineState:
    """Create the initial pipeline state for a user request."""
    return \
    {
        "user_request": user_request,
        "database_schema": DB.get_table_info(),
        "classification": None,
        "extracted_information": None,
        "current_query": None,
        "evaluation": None,
        "evaluation_feedback": None,
        "improvement_attempts": 0,
        "query_results": None,
        "final_answer": None,
        "outcome": None,
        "error_message": None,
    }


# Node: Agent 1 - Information extraction
def run_agent_1_extraction(state: PipelineState) -> dict:

    # Benchmark adapters may provide a validated, structured process-query
    # specification from workbook columns. Preserve it instead of re-parsing
    # the same fields from natural language.
    if (state.get("classification") == "IN_CONTEXT"
            and (state.get("extracted_information") or "").startswith((
                "TASK=NEXT_ACTIVITY_PREDICTION", "TASK=BOOLEAN_QUERY",
                "TASK=RELATIONAL_QUERY", "TASK=PROBABILITY_QUERY",
            ))):
        return {
            "classification": state["classification"],
            "extracted_information": state["extracted_information"],
        }

    classification, information = extract_information(
        state["user_request"], state["database_schema"]
    )

    return \
    {
        "classification": classification,
        "extracted_information": information,
    }


def route_after_extraction(state: PipelineState) -> str:
    if state["classification"] == "OUT_OF_CONTEXT":
        return "out_of_context"
    return "in_context"


# Node: Agent 2 - Query generation and correction
def run_agent_2(state: PipelineState) -> dict:

    query = generate_query(
        extracted_information=state["extracted_information"],
        database_schema=state["database_schema"],
        previous_query=state["current_query"],
        feedback=state["evaluation_feedback"],
    )

    return \
    {
        "current_query": query,
        "improvement_attempts": state["improvement_attempts"] + 1,
    }


# Node: Agent 3 - Query execution and result evaluation
def run_agent_3(state: PipelineState) -> dict:

    result = execute_and_evaluate(
        state["user_request"], state["current_query"],
        task_info=state.get("extracted_information"),
        database_schema=state.get("database_schema"),
    )

    update = {
        "evaluation": result["evaluation"],
        "evaluation_feedback": result["feedback"],
        "query_results": result["query_results"],
        "final_answer": result["final_answer"],
    }

    if result["evaluation"] == "SATISFIED":
        update["outcome"] = "SUCCESS"

    return update


def route_after_evaluation(state: PipelineState) -> str:
    if "SATISFIED" in (state["evaluation"] or ""):
        return "satisfied"
    if (state.get("extracted_information") or "").startswith("TASK=NEXT_ACTIVITY_PREDICTION"):
        # The structured NSP query is template-generated; retrying it verbatim
        # cannot repair an empty match and only repeats the same execution.
        return "attempt_limit_reached"
    if state["improvement_attempts"] >= MAX_ATTEMPTS:
        return "attempt_limit_reached"
    return "regenerate"


# Node: Out-of-context request
def handle_out_of_context(state: PipelineState) -> dict:
    return \
    {
        "outcome": "ERROR",
        "final_answer": "The request does not concern data available in the database, so I cannot answer it.",
        "error_message": "Request classified as out of context by Agent 1.",
    }


def handle_attempt_limit(state: PipelineState) -> dict:
    return \
    {
        "outcome": "ERROR",
        "final_answer": "I could not build a query that returns the requested data. "
                           "Try rephrasing the question with more details.",
        "error_message": f"Query results not judged satisfactory after "
                         f"{state['improvement_attempts']} attempts. "
                         f"Last feedback: {state['evaluation_feedback']}",
    }


# LangGraph construction
def build_pipeline():
    graph = StateGraph(PipelineState)

    graph.add_node("extract_request", run_agent_1_extraction)
    graph.add_node("generate_query", run_agent_2)
    graph.add_node("execute_and_evaluate", run_agent_3)
    graph.add_node("handle_out_of_context", handle_out_of_context)
    graph.add_node("handle_attempt_limit", handle_attempt_limit)

    graph.set_entry_point("extract_request")

    graph.add_conditional_edges(
        "extract_request",
        route_after_extraction,
        {
            "out_of_context": "handle_out_of_context",
            "in_context": "generate_query",
        },
    )

    graph.add_edge("generate_query", "execute_and_evaluate")

    graph.add_conditional_edges(
        "execute_and_evaluate",
        route_after_evaluation,
        {
            "satisfied": END,
            "regenerate": "generate_query",
            "attempt_limit_reached": "handle_attempt_limit",
        },
    )

    graph.add_edge("handle_out_of_context", END)
    graph.add_edge("handle_attempt_limit", END)

    return graph.compile().with_config(recursion_limit=2 * MAX_ATTEMPTS + 10)


PIPELINE = build_pipeline()
