# Orchestratore
from typing import TypedDict, Optional
from langgraph.graph import StateGraph, END
from agenti.request_agent import estrai_informazioni
from agenti.query_agent import genera_query
from agenti.response_agent import esegui_e_valuta
from utils.utils import DB


MAX_TENTATIVI = 6


# Shared pipeline state
class PipelineState(TypedDict):
    richiesta_utente: str
    schema_database: str
    classificazione: Optional[str]  # "FUORI_CONTESTO" | "IN_CONTESTO"
    informazioni_estratte: Optional[str]  # output of Agent 1
    query_corrente: Optional[str] # last query generated by Agent 2
    valutazione: Optional[str] # "SODDISFATTA" | "DA_RIGENERARE"
    feedback_valutazione: Optional[str]
    tentativi_miglioramento: int
    risultati_query: Optional[str]
    risposta_finale: Optional[str]
    esito: Optional[str]  # "successo" | "errore"
    messaggio_errore: Optional[str]  # cause of the error, if any


def crea_stato_iniziale(richiesta_utente: str) -> PipelineState:
    """Initial state of a run: PIPELINE.invoke(crea_stato_iniziale(richiesta))."""
    return \
    {
        "richiesta_utente": richiesta_utente,
        "schema_database": DB.get_table_info(),
        "classificazione": None,
        "informazioni_estratte": None,
        "query_corrente": None,
        "valutazione": None,
        "feedback_valutazione": None,
        "tentativi_miglioramento": 0,
        "risultati_query": None,
        "risposta_finale": None,
        "esito": None,
        "messaggio_errore": None,
    }


# Node "Agente 1 - Estrazione informazioni"
def esegui_agente_1_estrazione(state: PipelineState) -> dict:

    # Benchmark adapters may provide a validated, structured process-query
    # specification from workbook columns. Preserve it instead of re-parsing
    # the same fields from natural language.
    if (state.get("classificazione") == "IN_CONTESTO"
            and (state.get("informazioni_estratte") or "").startswith((
                "TASK=NEXT_ACTIVITY_PREDICTION", "TASK=BOOLEAN_QUERY",
            ))):
        return {
            "classificazione": state["classificazione"],
            "informazioni_estratte": state["informazioni_estratte"],
        }

    classificazione, informazioni = estrai_informazioni(
        state["richiesta_utente"], state["schema_database"]
    )

    return \
    {
        "classificazione": classificazione,
        "informazioni_estratte": informazioni,
    }


def route_dopo_estrazione(state: PipelineState) -> str:
    if state["classificazione"] == "FUORI_CONTESTO":
        return "fuori_contesto"
    return "in_contesto"


# Node "Agente 2 - Generazione/correzione query"
def esegui_agente_2(state: PipelineState) -> dict:

    query = genera_query(
        informazioni_estratte=state["informazioni_estratte"],
        schema_database=state["schema_database"],
        query_precedente=state["query_corrente"],
        feedback=state["feedback_valutazione"],
    )

    return \
    {
        "query_corrente": query,
        "tentativi_miglioramento": state["tentativi_miglioramento"] + 1,
    }


# Node "Agente 3 - Esecuzione e valutazione dei risultati"
def esegui_agente_3(state: PipelineState) -> dict:

    risultato = esegui_e_valuta(
        state["richiesta_utente"], state["query_corrente"],
        task_info=state.get("informazioni_estratte"),
    )

    aggiornamento = \
    {
        "valutazione": risultato["valutazione"],
        "feedback_valutazione": risultato["feedback"],
        "risultati_query": risultato["risultati_query"],
        "risposta_finale": risultato["risposta_finale"],
    }

    if risultato["valutazione"] == "SODDISFATTA":
        aggiornamento["esito"] = "successo"

    return aggiornamento


def route_dopo_valutazione(state: PipelineState) -> str:
    if "SODDISFATTA" in (state["valutazione"] or ""):
        return "soddisfatta"
    if (state.get("informazioni_estratte") or "").startswith("TASK=NEXT_ACTIVITY_PREDICTION"):
        # The structured NSP query is template-generated; retrying it verbatim
        # cannot repair an empty match and only repeats the same execution.
        return "limite_raggiunto"
    if state["tentativi_miglioramento"] >= MAX_TENTATIVI:
        return "limite_raggiunto"
    return "da_rigenerare"


# Node "Richiesta fuori contesto"
def gestisci_fuori_contesto(state: PipelineState) -> dict:
    return \
    {
        "esito": "errore",
        "risposta_finale": "La richiesta non riguarda i dati presenti nel database, quindi non posso rispondere.",
        "messaggio_errore": "Request classified as out of context by Agent 1.",
    }


def gestisci_limite_tentativi(state: PipelineState) -> dict:
    return \
    {
        "esito": "errore",
        "risposta_finale": "Non sono riuscito a costruire una query che restituisse i dati richiesti. "
                           "Prova a riformulare la domanda con maggiori dettagli.",
        "messaggio_errore": f"Query results not judged satisfactory after "
                            f"{state['tentativi_miglioramento']} attempts. "
                            f"Last feedback: {state['feedback_valutazione']}",
    }


# LangGraph construction
def costruisci_pipeline():
    graph = StateGraph(PipelineState)

    graph.add_node("esegui_agente_1_estrazione", esegui_agente_1_estrazione)
    graph.add_node("esegui_agente_2", esegui_agente_2)
    graph.add_node("esegui_agente_3", esegui_agente_3)
    graph.add_node("gestisci_fuori_contesto", gestisci_fuori_contesto)
    graph.add_node("gestisci_limite_tentativi", gestisci_limite_tentativi)

    graph.set_entry_point("esegui_agente_1_estrazione")

    graph.add_conditional_edges(
        "esegui_agente_1_estrazione",
        route_dopo_estrazione,
        {
            "fuori_contesto": "gestisci_fuori_contesto",
            "in_contesto": "esegui_agente_2",
        },
    )

    graph.add_edge("esegui_agente_2", "esegui_agente_3")

    graph.add_conditional_edges(
        "esegui_agente_3",
        route_dopo_valutazione,
        {
            "soddisfatta": END,
            "da_rigenerare": "esegui_agente_2",
            "limite_raggiunto": "gestisci_limite_tentativi",
        },
    )

    graph.add_edge("gestisci_fuori_contesto", END)
    graph.add_edge("gestisci_limite_tentativi", END)

    return graph.compile().with_config(recursion_limit=2 * MAX_TENTATIVI + 10)


PIPELINE = costruisci_pipeline()
